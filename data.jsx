const REQUIRED_FIELDS = [
  { key: "email",         label: "Email" },
  { key: "phone",         label: "Phone" },
  { key: "membership",    label: "Membership No." },
  { key: "ownership",     label: "Occupancy" },
  { key: "parking",       label: "Parking" },
];
function memberCompleteness(m) {
  const missing = REQUIRED_FIELDS.filter(f => !m[f.key]).map(f => f.key);
  return {
    pct: Math.round(((REQUIRED_FIELDS.length - missing.length) / REQUIRED_FIELDS.length) * 100),
    missing,
  };
}

