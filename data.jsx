// Strip honorific prefixes (MR./MRS./MS./SMT./DR./LATE) and return a clean display name.
const personName = (n) => (n || "").replace(/^\s*(MR|MRS|MS|SMT|DR|LATE)\.?\s+/i, "").trim();

// First initial of name + first initial of second word, after stripping honorifics.
const personInitials = (n) => {
  const stripped = personName(n);
  const parts = stripped.split(/[\s.]+/).filter(Boolean);
  return ((parts[0] || "")[0] || "") + ((parts[1] || "")[0] || "");
};

// First given name only (handy for greetings).
const personFirstName = (n) => (personName(n).split(/[\s.]+/)[0] || "");

